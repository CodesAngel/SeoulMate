"""K-drama Wrapped: a fan's year in review, counted from their list and ratings.

Every number is a plain count over the fan's watchlist, ratings and the catalog
(credits, genres, keywords). Nothing is generated by a model.
"""

from collections import Counter, defaultdict
from datetime import datetime, timezone
import math
import re
import uuid

from fastapi import APIRouter, Depends, HTTPException, Query, status
from pydantic import BaseModel, Field
from sqlalchemy import func, select
from sqlalchemy.orm import Session

from auth import AuthenticatedUser, require_user
from database.models import (
    Drama,
    DramaCredit,
    DramaGenre,
    DramaKeyword,
    Genre,
    Keyword,
    Person,
    Profile,
    Rating,
    WatchlistItem,
    WrappedShare,
)
from database.session import get_db
from user_library import _storage_url


router = APIRouter(tags=["Wrapped"])

FIRST_YEAR = 2026
MIN_DRAMAS = 3
DEFAULT_EPISODE_MINUTES = 60
LEAD_BILLING_MAX = 2  # billing_order is 0-based: 0-2 = the first three names
MOSAIC_LIMIT = 18

# Keyword tags that describe the format or source, not the story.
NON_TROPE_KEYWORDS = {
    "web series",
    "short length series",
    "miniseries",
    "filmed vertically",
    "web release",
    "multiple mains",
    "multiple couples",
    "character development",
    "flashback to past",
    "student supporting character",
    "slight romance",
    "historical fiction",
}
NON_TROPE_PATTERNS = ("adapted from", "[real life]", "[drama life]", "remake", "sequel", "spin-off")

# Fan types: (name, genres, share needed, sentence). The one that clears its
# bar by the widest margin wins; "The Binger" and "The Explorer" are fallbacks.
FAN_TYPES = [
    ("The Romantic", {"Romance"}, 0.6, "Romance in {n} of your {total} dramas ({pct}%)."),
    ("The Sleuth", {"Thriller", "Mystery", "Crime"}, 0.4, "Thrillers, mysteries or crime in {n} of your {total} dramas."),
    ("The Time Traveller", {"Historical"}, 0.35, "Historical stories in {n} of your {total} dramas."),
    ("The Dreamer", {"Fantasy", "Supernatural", "Sci-Fi"}, 0.4, "Fantasy and the supernatural in {n} of your {total} dramas."),
    ("The Comfort Watcher", {"Comedy", "Life"}, 0.55, "Comedy and slice of life in {n} of your {total} dramas."),
    ("The Tear Collector", {"Melodrama"}, 0.35, "Melodrama in {n} of your {total} dramas. Tissues ready."),
    ("The Thrill Seeker", {"Action"}, 0.4, "Action in {n} of your {total} dramas."),
]
BINGER_HOURS = 200

_DURATION_HOURS = re.compile(r"(\d+)\s*hr")
_DURATION_MINUTES = re.compile(r"(\d+)\s*min")
_keyword_idf_cache: dict = {}


class ShareRequest(BaseModel):
    year: int = Field(ge=FIRST_YEAR, le=2100)
    show_name: bool = True


def episode_minutes(duration: str | None) -> int:
    """'1 hr. 10 min.' -> 70, '45 min.' -> 45; 60 when blank or unreadable."""
    if not duration:
        return DEFAULT_EPISODE_MINUTES
    hours = _DURATION_HOURS.search(duration)
    minutes = _DURATION_MINUTES.search(duration)
    total = (int(hours.group(1)) * 60 if hours else 0) + (int(minutes.group(1)) if minutes else 0)
    return total or DEFAULT_EPISODE_MINUTES


def is_trope_keyword(name: str) -> bool:
    lowered = name.lower()
    if lowered in NON_TROPE_KEYWORDS:
        return False
    return not any(pattern in lowered for pattern in NON_TROPE_PATTERNS)


def _current_year() -> int:
    return datetime.now(timezone.utc).year


def _check_year(year: int) -> None:
    if year < FIRST_YEAR or year > _current_year():
        raise HTTPException(
            status_code=status.HTTP_404_NOT_FOUND,
            detail=f"Wrapped covers {FIRST_YEAR} to {_current_year()}",
        )


def _year_bounds(year: int) -> tuple[datetime, datetime]:
    return (
        datetime(year, 1, 1, tzinfo=timezone.utc),
        datetime(year + 1, 1, 1, tzinfo=timezone.utc),
    )


def _drama_card(drama: Drama) -> dict:
    return {
        "drama_id": drama.id,
        "title": drama.title,
        "aired": drama.aired,
        "episodes": drama.episodes,
        "poster_url": _storage_url(drama.poster_thumbnail_key),
        "poster_original_url": _storage_url(drama.poster_original_key),
    }


def _keyword_idf(db: Session) -> tuple[dict[int, float], float]:
    """IDF per keyword over the whole catalog, cached until the catalog size changes."""
    total = db.scalar(select(func.count()).select_from(Drama)) or 1
    if _keyword_idf_cache.get("total") != total:
        rows = db.execute(
            select(DramaKeyword.keyword_id, func.count()).group_by(DramaKeyword.keyword_id)
        ).all()
        _keyword_idf_cache["total"] = total
        _keyword_idf_cache["idf"] = {
            keyword_id: math.log(total / count) for keyword_id, count in rows if count
        }
    return _keyword_idf_cache["idf"], float(total)


def _top_actor(db: Session, finished: list[tuple[WatchlistItem, Drama]], user_ratings: dict[int, float]) -> dict | None:
    drama_ids = [drama.id for _, drama in finished]
    rows = db.execute(
        select(DramaCredit.drama_id, Person.name)
        .join(Person, Person.id == DramaCredit.person_id)
        .where(
            DramaCredit.drama_id.in_(drama_ids),
            DramaCredit.role == "actor",
            DramaCredit.billing_order <= LEAD_BILLING_MAX,
        )
    ).all()
    if not rows:
        return None
    dramas_by_id = {drama.id: drama for _, drama in finished}
    order = {drama.id: index for index, (_, drama) in enumerate(finished)}
    by_actor: dict[str, list[int]] = defaultdict(list)
    for drama_id, name in rows:
        by_actor[name].append(drama_id)

    def avg_rating(ids: list[int]) -> float:
        scores = [user_ratings[i] for i in ids if i in user_ratings]
        return sum(scores) / len(scores) if scores else 0.0

    def popularity(ids: list[int]) -> int:
        return sum(dramas_by_id[i].watchers or 0 for i in ids)

    ranked = sorted(
        by_actor.items(),
        key=lambda pair: (-len(pair[1]), -avg_rating(pair[1]), -popularity(pair[1]), pair[0]),
    )
    name, ids = ranked[0]
    ids.sort(key=lambda i: order[i])
    result = {
        "name": name,
        "count": len(ids),
        "dramas": [_drama_card(dramas_by_id[i]) for i in ids],
        "tie_with": None,
        "tie_broken_by": None,
    }
    if len(ranked) > 1 and len(ranked[1][1]) == len(ids) and len(ids) > 1:
        runner_name, runner_ids = ranked[1]
        result["tie_with"] = {"name": runner_name, "count": len(runner_ids)}
        result["tie_broken_by"] = (
            "ratings" if avg_rating(ids) != avg_rating(runner_ids) else "popularity"
        )
    return result


def _top_trope(db: Session, finished: list[tuple[WatchlistItem, Drama]]) -> dict | None:
    drama_ids = [drama.id for _, drama in finished]
    rows = db.execute(
        select(Keyword.id, Keyword.name)
        .join(DramaKeyword, DramaKeyword.keyword_id == Keyword.id)
        .where(DramaKeyword.drama_id.in_(drama_ids))
    ).all()
    counts: Counter = Counter()
    names: dict[int, str] = {}
    for keyword_id, name in rows:
        if is_trope_keyword(name):
            counts[keyword_id] += 1
            names[keyword_id] = name
    if not counts:
        return None
    idf, _ = _keyword_idf(db)
    # A tag in only one drama isn't a pattern, unless nothing repeats at all.
    pool = [k for k, c in counts.items() if c >= 2] or list(counts)
    # sqrt(IDF) damps very common tags without letting a rare tag in 3 dramas
    # beat a fitting one in 4.
    ranked = sorted(
        pool,
        key=lambda k: (-(counts[k] * math.sqrt(idf.get(k, 0.0))), -counts[k], names[k]),
    )
    top, others = ranked[0], ranked[1:4]
    return {
        "name": names[top],
        "count": counts[top],
        "others": [{"name": names[k], "count": counts[k]} for k in others],
    }


def _genres(db: Session, finished: list[tuple[WatchlistItem, Drama]]) -> list[dict]:
    drama_ids = [drama.id for _, drama in finished]
    rows = db.execute(
        select(Genre.name, func.count())
        .join(DramaGenre, DramaGenre.genre_id == Genre.id)
        .where(DramaGenre.drama_id.in_(drama_ids))
        .group_by(Genre.name)
    ).all()
    ranked = sorted(rows, key=lambda row: (-row[1], row[0]))
    return [{"name": name, "count": count} for name, count in ranked]


def fan_type(genre_counts: dict[str, int], total: int, hours: int) -> dict:
    best = None
    for name, genres, needed, sentence in FAN_TYPES:
        # A drama counts once even when it has two of the genres.
        n = genre_counts.get("|".join(sorted(genres)), 0)
        share = n / total if total else 0
        if share >= needed:
            margin = share / needed
            if best is None or margin > best[0]:
                best = (margin, name, sentence.format(n=n, total=total, pct=round(share * 100)))
    if best:
        return {"name": best[1], "description": best[2]}
    if hours >= BINGER_HOURS:
        return {"name": "The Binger", "description": f"{hours} hours of K-dramas this year. That's commitment."}
    return {"name": "The Explorer", "description": "No single genre took over your year. You go where the story is."}


def _fan_type_counts(db: Session, finished: list[tuple[WatchlistItem, Drama]]) -> dict[str, int]:
    """For each fan-type genre group, how many finished dramas have any of its genres."""
    drama_ids = [drama.id for _, drama in finished]
    rows = db.execute(
        select(DramaGenre.drama_id, Genre.name)
        .join(Genre, Genre.id == DramaGenre.genre_id)
        .where(DramaGenre.drama_id.in_(drama_ids))
    ).all()
    genres_by_drama: dict[int, set[str]] = defaultdict(set)
    for drama_id, name in rows:
        genres_by_drama[drama_id].add(name)
    counts = {}
    for _, genres, _, _ in FAN_TYPES:
        key = "|".join(sorted(genres))
        counts[key] = sum(1 for names in genres_by_drama.values() if names & genres)
    return counts


def build_wrapped(db: Session, user_id, year: int) -> dict:
    start, end = _year_bounds(year)
    rows = db.execute(
        select(WatchlistItem, Drama)
        .join(Drama, Drama.id == WatchlistItem.drama_id)
        .where(WatchlistItem.user_id == user_id)
    ).all()
    finished = sorted(
        (
            (item, drama)
            for item, drama in rows
            if item.status == "completed"
            and item.completed_at is not None
            and start <= item.completed_at < end
        ),
        key=lambda pair: pair[0].completed_at,
    )
    base = {"year": year, "required": MIN_DRAMAS, "finished": len(finished)}
    if len(finished) < MIN_DRAMAS:
        return {**base, "unlocked": False}

    # Episodes: every episode of a finished drama, plus progress on unfinished
    # ones touched this year.
    episodes = 0
    minutes = 0
    for _, drama in finished:
        count = drama.episodes or 0
        episodes += count
        minutes += count * episode_minutes(drama.duration)
    for item, drama in rows:
        if (
            item.status != "completed"
            and item.episodes_watched
            and start <= item.updated_at < end
        ):
            count = min(item.episodes_watched, drama.episodes or item.episodes_watched)
            episodes += count
            minutes += count * episode_minutes(drama.duration)
    hours = round(minutes / 60)

    rating_rows = db.execute(
        select(Rating, Drama)
        .join(Drama, Drama.id == Rating.drama_id)
        .where(Rating.user_id == user_id)
    ).all()
    user_ratings = {rating.drama_id: float(rating.rating) for rating, _ in rating_rows}

    finished_at = {drama.id: item.completed_at for item, drama in finished}
    far_future = datetime(9999, 1, 1, tzinfo=timezone.utc)
    year_ratings = [
        (rating, drama)
        for rating, drama in rating_rows
        if start <= rating.updated_at < end or drama.id in finished_at
    ]
    top_rated = None
    if year_ratings:
        rating, drama = sorted(
            year_ratings,
            key=lambda pair: (
                -float(pair[0].rating),
                finished_at.get(pair[1].id, far_future),
                pair[0].created_at,
            ),
        )[0]
        top_rated = {**_drama_card(drama), "rating": float(rating.rating)}

    genres = _genres(db, finished)
    profile = db.get(Profile, user_id)

    return {
        **base,
        "unlocked": True,
        "display_name": profile.display_name if profile else None,
        "totals": {"dramas": len(finished), "episodes": episodes, "hours": hours},
        "posters": [_drama_card(drama) for _, drama in finished[-MOSAIC_LIMIT:]],
        "top_actor": _top_actor(db, finished, user_ratings),
        "top_trope": _top_trope(db, finished),
        "genres": genres[:5],
        "fan_type": fan_type(_fan_type_counts(db, finished), len(finished), hours),
        "top_rated": top_rated,
    }


def _share_for(db: Session, user_id, year: int) -> WrappedShare | None:
    return db.scalar(
        select(WrappedShare).where(WrappedShare.user_id == user_id, WrappedShare.year == year)
    )


def _share_payload(share: WrappedShare) -> dict:
    return {
        "id": str(share.id),
        "year": share.year,
        "show_name": share.show_name,
        "created_at": share.created_at,
        "updated_at": share.updated_at,
    }


@router.get("/me/wrapped")
def get_my_wrapped(
    year: int = Query(default_factory=_current_year),
    current_user: AuthenticatedUser = Depends(require_user),
    db: Session = Depends(get_db),
):
    _check_year(year)
    stats = build_wrapped(db, current_user.id, year)
    share = _share_for(db, current_user.id, year)
    return {**stats, "share": _share_payload(share) if share else None}


@router.post("/me/wrapped/share")
def share_my_wrapped(
    request: ShareRequest,
    current_user: AuthenticatedUser = Depends(require_user),
    db: Session = Depends(get_db),
):
    """Saves (or refreshes) the public snapshot; the link stays the same."""
    _check_year(request.year)
    stats = build_wrapped(db, current_user.id, request.year)
    if not stats["unlocked"]:
        raise HTTPException(
            status_code=status.HTTP_400_BAD_REQUEST,
            detail=f"Wrapped unlocks after {MIN_DRAMAS} finished dramas",
        )
    if not request.show_name:
        stats["display_name"] = None
    share = _share_for(db, current_user.id, request.year)
    if share is None:
        share = WrappedShare(user_id=current_user.id, year=request.year)
        db.add(share)
    share.show_name = request.show_name
    share.stats_json = stats
    db.commit()
    db.refresh(share)
    return {"share": _share_payload(share)}


@router.delete("/me/wrapped/share", status_code=status.HTTP_204_NO_CONTENT)
def delete_my_wrapped_share(
    year: int = Query(ge=FIRST_YEAR, le=2100),
    current_user: AuthenticatedUser = Depends(require_user),
    db: Session = Depends(get_db),
):
    share = _share_for(db, current_user.id, year)
    if share is not None:
        db.delete(share)
        db.commit()


@router.get("/wrapped/shares/{share_id}")
def get_wrapped_share(share_id: str, db: Session = Depends(get_db)):
    """Public: the saved snapshot only, never the owner's live list."""
    try:
        key = uuid.UUID(share_id)
    except ValueError:
        raise HTTPException(status_code=status.HTTP_404_NOT_FOUND, detail="Not found")
    share = db.get(WrappedShare, key)
    if share is None:
        raise HTTPException(status_code=status.HTTP_404_NOT_FOUND, detail="Not found")
    return {"share": _share_payload(share), "stats": share.stats_json}
